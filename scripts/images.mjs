// ─────────────────────────────────────────────────────────────────────────────
// images.mjs: the photos of the current site (reference/current-site/images, pulled 10/11/2026) and,
// later, the client's Drive photos (reference/drive, when someone drops them there) → public/images
// as WebP at the size they are shown (≤ 1920) + a -sm for phones, and src/data/images.gen.ts with
// their real pixel sizes. Logos stay PNG (resized). Run: `npm run images`.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'public', 'images')
fs.mkdirSync(out, { recursive: true })
const SOURCES = ['reference/current-site/images', 'reference/drive'].map((d) => path.join(root, d)).filter((d) => fs.existsSync(d))
const SKIP = /^(icon-|f7f4fb)/ // the old site's clip-art icons and a screenshot of it
const KEEP = /^prof_cut$/ // kept at full quality (see below)

const sizes = {}
const key = (f) => f.replace(/\.(jpe?g|png|webp)$/i, '').replace(/[^a-z0-9]+/gi, '_').replace(/^_|_$/g, '').toLowerCase()
for (const dir of SOURCES) {
  for (const f of fs.readdirSync(dir).filter((x) => /\.(jpe?g|png|webp)$/i.test(x) && !SKIP.test(x))) {
    const src = path.join(dir, f), name = key(f), meta = await sharp(src).metadata()
    if (/^logo/.test(name)) {
      const info = await sharp(src).resize({ width: 640 }).png({ compressionLevel: 9 }).toFile(path.join(out, `${name}.png`))
      sizes[name] = { w: info.width, h: info.height, ext: 'png' }
      continue
    }
    // the coach's cutout (Adryan, 11/11: re-encoding it at 74 and serving a 480 px copy blurred it):
    // the client's file as it came, one size only
    if (KEEP.test(name)) {
      const dst = path.join(out, `${name}.webp`)
      if (/\.webp$/i.test(f)) fs.copyFileSync(src, dst)
      else await sharp(src).rotate().webp({ quality: 95, effort: 6 }).toFile(dst)
      fs.rmSync(path.join(out, `${name}-sm.webp`), { force: true })
      sizes[name] = { w: meta.width, h: meta.height }
      continue
    }
    const w = Math.min(1920, meta.width)
    const info = await sharp(src).rotate().resize({ width: w }).webp({ quality: 74, effort: 6 }).toFile(path.join(out, `${name}.webp`))
    const sm = Math.min(w, meta.width > 1000 ? 800 : 480)
    await sharp(src).rotate().resize({ width: sm }).webp({ quality: 70, effort: 6 }).toFile(path.join(out, `${name}-sm.webp`))
    sizes[name] = { w: info.width, h: info.height, sm }
  }
}
fs.writeFileSync(path.join(root, 'src', 'data', 'images.gen.ts'), `// generated by scripts/images.mjs\nexport const IMG = ${JSON.stringify(sizes, null, 2)} as const\n`)
console.log(`images: ${Object.keys(sizes).length} → public/images`)
