// ─────────────────────────────────────────────────────────────────────────────
// blog.mjs: the 33 posts of the current blog (reference/current-site/content.json, pulled 10/11/2026)
// → src/data/blog.gen.ts, same slugs (/blog/<slug>), so the URLs Google knows keep working.
// Each post on the old site is: category, h1, "date · byline", body, then a "Train with us in Hyannis"
// block; the new site draws its own closing CTA, so that block goes. No em dashes in visitor copy.
// Run: `node scripts/blog.mjs`.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(fs.readFileSync(path.join(root, 'reference/current-site/content.json'), 'utf8'))
const clean = (s) => s.replace(/\s*—\s*/g, ', ').replace(/\s+/g, ' ').trim()
// the photos the news posts carry on the old site (downloaded with the rest)
const COVERS = { '2026-boston-fall-international-open': 'boston_fall_open_2026_team', 'david-cia-ibjjf-pan-kids-no-gi-2026': 'boston_fall_open_2026_kids' }
// the other posts had one generic picture on the old site: each gets a real academy photo, picked by
// its subject and rotated so neighbours never repeat (a grid of identical blocks reads as a template)
const BY_TOPIC = [
  [/capoeira/, ['capoeira_1', 'capoeira']], [/judo/, ['judo_2', 'judo_1']], [/box/, ['boxing', 'box_1']],
  [/women/, ['women_2', 'women_1']], [/kid|teen|family|adhd|focus|parent/, ['kids_2', 'kids', 'kids_1', 'prof_1']],
  [/self-defense|safe|injur/, ['women_1', 'adult_2', 'judo_1']],
]
const POOL = ['adult_2', 'mission', 'kids_2', 'about_2', 'adult', 'kids_1', 'adult_1', 'about_1', 'women_2', 'hero', 'prof_1', 'kids']
let rot = 0
const used = []
const coverOf = (slug, category) => {
  if (COVERS[slug]) return COVERS[slug]
  const hit = BY_TOPIC.find(([re]) => re.test(slug) || re.test(category.toLowerCase()))
  const list = hit ? hit[1] : [...POOL.slice(rot % POOL.length), ...POOL.slice(0, rot++ % POOL.length)]
  // the first option not used by the two previous posts
  const pick = list.find((x) => !used.slice(-2).includes(x)) ?? POOL[rot++ % POOL.length]
  used.push(pick); return pick
}

const posts = src.posts.map((p) => {
  const b = p.blocks
  const category = clean(b[0].x)
  const date = clean(b[2].x.split('·')[0])
  let body = b.slice(3).map((x) => ({ t: x.t === 'h1' ? 'h2' : x.t, x: clean(x.x) }))
  const cut = body.findIndex((x) => x.t === 'h2' && /^Train with us in Hyannis/i.test(x.x))
  if (cut >= 0) body = body.slice(0, cut)
  return { slug: p.slug, title: clean(p.title), desc: clean(p.desc ?? body.find((x) => x.t === 'p')?.x ?? ''), category, date, iso: new Date(date).toISOString().slice(0, 10), cover: null, body }
}).sort((a, z) => z.iso.localeCompare(a.iso))
for (const p of posts) p.cover = coverOf(p.slug, p.category)

fs.writeFileSync(path.join(root, 'src/data/blog.gen.ts'), `// generated by scripts/blog.mjs from the old site's blog\nexport type Block = { t: string; x: string }\nexport type Post = { slug: string; title: string; desc: string; category: string; date: string; iso: string; cover: string | null; body: Block[] }\nexport const POSTS: Post[] = ${JSON.stringify(posts, null, 1)}\n`)
console.log(`blog: ${posts.length} posts · ${[...new Set(posts.map((p) => p.category))].join(', ')}`)
